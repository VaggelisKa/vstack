"""Generates the `claude plugin eval` cases in evals/ from skills/*/evals/evals.json.

skills/<skill>/evals/evals.json is the only source of eval cases (the skill-creator format). Each case
may carry an `eval` object that says how `claude plugin eval` runs and grades it:

    "eval": {
      "slug": "no-merge-on-land",          # the case is evals/<skill>-<id>-<slug>/
      "tags": ["smoke"],                   # the skill's name is always a tag
      "prompt": "...",                     # what the agent is sent; defaults to the case's prompt
      "fixture": "pr-green",               # evals/_harness/fixtures/<name>.json; omit for no workspace setup
      "patch": {...},                      # deep-merged into the fixture (objects merge, null deletes, lists replace)
      "graders": [...],                    # deterministic graders, below
      "runs": 3, "max_turns": 60, "timeout_seconds": 900, "allowed_tools": [...]
    }

Each expectation becomes an llm grader over the trace unless a grader lists its index (0-based) in
`covers`. Grader shapes (name is required, weight optional):

    {"gh": "<regex>"}                        .vstack-eval/gh-calls.log matches (multiline); "absent": true
                                             for no match, "count": N for exactly N matches
    {"trace": "<regex>"} / {"reply": "<regex>"}   the whole trace / the final message ("absent" as above)
    {"file": "<path>", "pattern": "<regex>"} a file in the run's working directory ("absent" as above)
    {"exists": "<glob>"}                     a file the run created ("absent": true for none)
    {"tool": "Read", "input": "<regex>", "min": 0, "max": 0}   tool calls, scored in both arms
    {"skill": "babysit", "fires": true}      the Skill tool was (or was not) called for vstack:<skill>
    {"llm": "<criteria>", "focus": "trace"}  an extra llm grader

Usage: python3 evals/_harness/sync.py            # write evals/
       python3 evals/_harness/sync.py --check    # exit 1 if evals/ is out of date (CI)
"""
import argparse
import copy
import filecmp
import json
import pathlib
import re
import shutil
import sys
import tempfile

HARNESS = pathlib.Path(__file__).resolve().parent
ROOT = HARNESS.parent.parent
EVALS = HARNESS.parent
MARK = "# Generated by evals/_harness/sync.py"
LOG = ".vstack-eval/gh-calls.log"
RESERVED = {"_harness", "results", "mocks"}

GH_TOOLS = ["Bash", "Read", "Write", "Edit", "Glob", "Grep", "Skill", "Agent"]
DEFAULTS = {
    "babysit": {"allowed_tools": GH_TOOLS, "max_turns": 80, "timeout_seconds": 1200},
    "autonomous-merge": {"allowed_tools": GH_TOOLS, "max_turns": 150, "timeout_seconds": 2400},
    "review": {"allowed_tools": GH_TOOLS, "max_turns": 80, "timeout_seconds": 1500},
    "remove-comments": {"allowed_tools": GH_TOOLS, "max_turns": 60, "timeout_seconds": 900},
    "html-plan": {"allowed_tools": GH_TOOLS, "max_turns": 60, "timeout_seconds": 1200},
}
# Both arms get this: an eval run is one non-interactive session, so a skill that would wait for
# GitHub or a person has to finish with what it has.
NO_WAITING = ("This is a non-interactive evaluation run in a sandbox: nobody will answer questions, no "
              "time passes between your polls, and there is no way to schedule a wake-up. Where a skill "
              "says to wait for the next poll, poll once more right away; if nothing changed, stop and "
              "write the final report as the skill describes.")
WAITS = {"babysit", "autonomous-merge"}


def deep_merge(base, patch):
    out = copy.deepcopy(base)
    for k, v in patch.items():
        if v is None:
            out.pop(k, None)
        elif isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = deep_merge(out[k], v)
        else:
            out[k] = copy.deepcopy(v)
    return out


def matcher(g, key, target, flags=""):
    out = {"name": g["name"], "type": "regex", "target": target, "pattern": g[key]}
    if flags or g.get("flags"):
        out["flags"] = g.get("flags", flags)
    if g.get("absent"):
        out["match"] = "not_contains"
    elif "count" in g:
        out["match"] = f"count:{g['count']}"
    return out


def grader(g, skill):
    if "gh" in g:
        out = matcher(g, "gh", {"source": "file", "path": LOG}, "m")
    elif "trace" in g:
        out = matcher(g, "trace", "trace")
    elif "reply" in g:
        out = matcher(g, "reply", "last_message", "i")
    elif "file" in g:
        out = {**matcher({**g, "p": g["pattern"]}, "p", {"source": "file", "path": g["file"]})}
    elif "exists" in g:
        out = {"name": g["name"], "type": "file_exists", "path": g["exists"], "exists": not g.get("absent")}
    elif "tool" in g:
        out = {"name": g["name"], "type": "tool_used", "tool": g["tool"], "arm": "both"}
        for k in ("min", "max"):
            if k in g:
                out[k] = g[k]
        if "max" in g and "min" not in g:  # tool_used's min defaults to 1
            out["min"] = 0
        if "input" in g:
            out["input_match"] = g["input"]
    elif "skill" in g:
        fires = g.get("fires", True)
        out = {"name": g["name"], "type": "tool_used", "tool": "Skill", "arm": "both",
               "input_match": rf'"skill":\s*"(vstack:)?{g["skill"]}"',
               "min": 1 if fires else 0, **({} if fires else {"max": 0})}
    elif "llm" in g:
        out = {"name": g["name"], "type": "llm", "criteria": g["llm"], "focus": g.get("focus", "trace")}
    else:
        raise SystemExit(f"sync: unknown grader shape in {skill}: {g}")
    if "weight" in g:
        out["weight"] = g["weight"]
    return out


def expectation_grader(i, text, case, prompt):
    return {"name": f"expect-{i + 1}", "type": "llm", "focus": "trace",
            "criteria": (f"The user's request was:\n{prompt}\n\nThe intended outcome: {case['expected_output']}\n\n"
                         f"PASS only if the trace shows this held: {text}\n"
                         "FAIL if it did not hold, or if the trace does not show enough to tell.")}


def build(skill, case):
    ev = case.get("eval", {})
    d = DEFAULTS.get(skill, DEFAULTS["review"])
    name = f"{skill}-{case['id']:02d}" + (f"-{ev['slug']}" if ev.get("slug") else "")
    prompt = ev.get("prompt", case["prompt"])
    graders = [grader(g, skill) for g in ev.get("graders", [])]
    covered = {i for g in ev.get("graders", []) for i in g.get("covers", [])}
    graders += [expectation_grader(i, t, case, prompt) for i, t in enumerate(case["expectations"]) if i not in covered]
    names = [g["name"] for g in graders]
    if len(set(names)) != len(names):
        raise SystemExit(f"sync: {name}: duplicate grader names {names}")
    doc = {"schema_version": "1.1", "name": name, "description": case["expected_output"],
           "tags": [skill, *ev.get("tags", [])], "runs": ev.get("runs", 3),
           "expected_outcome": case["expected_output"]}
    fixture = None
    if "fixture" in ev or "patch" in ev:
        base = json.loads((HARNESS / "fixtures" / f"{ev['fixture']}.json").read_text()) if ev.get("fixture") else {}
        fixture = deep_merge(base, ev.get("patch", {}))
        doc["context"] = {"scaffold_script": "scaffold.sh"}
    execution = {"prompt": prompt, "max_turns": ev.get("max_turns", d["max_turns"]),
                 "timeout_seconds": ev.get("timeout_seconds", d["timeout_seconds"]),
                 "allowed_tools": ev.get("allowed_tools", d["allowed_tools"])}
    if skill in WAITS and ev.get("no_waiting", True):
        execution["append_system_prompt"] = NO_WAITING
    doc["execution"] = execution
    doc["graders"] = graders
    return name, doc, fixture


# ---- a small YAML writer: block style, every scalar JSON-quoted (valid YAML) ----

def yaml(v, indent=0):
    pad = " " * indent
    if isinstance(v, dict):
        lines = []
        for k, x in v.items():
            if isinstance(x, (dict, list)) and x:
                lines.append(f"{pad}{k}:\n{yaml(x, indent + 2)}")
            else:
                lines.append(f"{pad}{k}: {scalar(x)}")
        return "\n".join(lines)
    lines = []
    for x in v:
        if isinstance(x, dict) and x:
            body = yaml(x, indent + 2)
            lines.append(f"{pad}- {body[indent + 2:]}")
        else:
            lines.append(f"{pad}- {scalar(x)}")
    return "\n".join(lines)


def scalar(x):
    if x == {} or x == []:
        return json.dumps(x)
    if isinstance(x, str) and re.fullmatch(r"[A-Za-z][\w./-]*", x) and x not in ("true", "false", "null", "yes", "no"):
        return x
    return json.dumps(x, ensure_ascii=False)


def generate(out):
    for f in sorted(ROOT.glob("skills/*/evals/evals.json")):
        data = json.loads(f.read_text())
        skill = data["skill_name"]
        for case in data["evals"]:
            name, doc, fixture = build(skill, case)
            d = out / name
            if d.exists():
                raise SystemExit(f"sync: two cases are named {name}")
            d.mkdir(parents=True)
            src = f.relative_to(ROOT)
            (d / "case.yaml").write_text(f"{MARK} from {src} (id {case['id']}).\n"
                                         f"# Do not edit: change {src} and run python3 evals/_harness/sync.py.\n"
                                         + yaml(doc) + "\n")
            if fixture is not None:
                (d / "fixture.json").write_text(json.dumps(fixture, indent=2, ensure_ascii=False) + "\n")
                (d / "scaffold.sh").write_text(f"{MARK}. Builds the run's workspace from fixture.json.\n"
                                               'exec python3 "$(dirname "$0")/../_harness/scaffold.py" '
                                               '"$(dirname "$0")/fixture.json"\n')


def case_dirs(root):
    return sorted(p.name for p in root.iterdir() if p.is_dir() and p.name not in RESERVED and not p.name.startswith("."))


def same(a, b):
    c = filecmp.dircmp(a, b)
    return not (c.left_only or c.right_only or c.diff_files or c.funny_files) and \
        all(same(a / s, b / s) for s in c.common_dirs)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if evals/ doesn't match evals.json")
    args = ap.parse_args()
    with tempfile.TemporaryDirectory() as tmp:
        fresh = pathlib.Path(tmp)
        generate(fresh)
        want, have = case_dirs(fresh), case_dirs(EVALS)
        stale = [n for n in have if n not in want]
        changed = [n for n in want if n not in have or not same(fresh / n, EVALS / n)]
        if args.check:
            if stale or changed:
                print("evals/ is out of date with skills/*/evals/evals.json. Run: python3 evals/_harness/sync.py",
                      file=sys.stderr)
                for n in stale:
                    print(f"  not generated from any evals.json case: evals/{n}", file=sys.stderr)
                for n in changed:
                    print(f"  differs: evals/{n}", file=sys.stderr)
                return 1
            print(f"evals/ is up to date ({len(want)} cases).")
            return 0
        for n in stale:
            if (EVALS / n / "case.yaml").exists() and (EVALS / n / "case.yaml").read_text().startswith(MARK) \
                    or not (EVALS / n / "case.yaml").exists() and (EVALS / n / "prompt.md").exists():
                shutil.rmtree(EVALS / n)
            else:
                print(f"sync: left evals/{n} alone (not generated); move it into an evals.json", file=sys.stderr)
        for n in changed:
            shutil.rmtree(EVALS / n, ignore_errors=True)
            shutil.copytree(fresh / n, EVALS / n)
        print(f"evals/: {len(want)} cases, {len(changed)} written, {len(stale)} removed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
